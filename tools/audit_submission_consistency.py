"""Audit the machine-readable canonical A11yPreserve submission state.

The audit intentionally treats historical V1/V2 records as provenance, not as
inputs to the current V3 denominator.  It derives all counts from records and
fails when stored summaries, manifests, or supplementary experiment counts
disagree.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
CANONICAL = ROOT / "results" / "V3_PRIMARY_RESULTS.json"
CORE_MANIFEST = ROOT / "corpus" / "FROZEN_CORPUS_MANIFEST.json"
VARIANT_RESULTS = ROOT / "v3" / "variant_set_b" / "V3_VARIANT_SET_B_FINAL_RESULTS.json"
HISTORICAL = ROOT / "results" / "full_experiment" / "FINAL_EVIDENCE_AWARE_RESULTS.json"
CALIBRATION = ROOT / "final_strengthening" / "COMPARATOR_CALIBRATION.json"
REPEATABILITY = ROOT / "v3" / "google_repeatability" / "REPEATABILITY_RESULTS.json"
INTEGRATED = ROOT / "integrated_study" / "INTEGRATED_RESULTS.json"
MANUSCRIPT_RESULTS = ROOT / "submission" / "ICST2027_V3" / "sections" / "results.tex"


def load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def check(condition: bool, label: str, details: str, failures: list[str]) -> str:
    status = "PASS" if condition else "FAIL"
    if not condition:
        failures.append(f"{label}: {details}")
    return f"| {label} | {status} | {details} |"


def audit() -> tuple[list[str], list[str]]:
    failures: list[str] = []
    rows: list[str] = []
    result = load(CANONICAL)
    core_manifest = load(CORE_MANIFEST)
    variant = load(VARIANT_RESULTS)
    historical = load(HISTORICAL)
    calibration = load(CALIBRATION)
    repeatability = load(REPEATABILITY)
    integrated = load(INTEGRATED)
    manuscript_text = MANUSCRIPT_RESULTS.read_text(encoding="utf-8")

    records = result["records"]
    derived_counts = Counter(row["final_evidence_aware_result"] for row in records)
    stored_counts = Counter(result["counts"])
    derived_pipelines = Counter(row["pipeline"] for row in records)
    derived_arms = Counter(row["study_arm"] for row in records)
    feature_ids = {row.get("fixture") for row in records if row["study_arm"] == "Core"}
    contract_files = sorted((ROOT / "contracts").glob("F*.json"))

    rows.append("# Final consistency audit")
    rows.append("")
    rows.append("Generated by `tools/audit_submission_consistency.py`.")
    rows.append("")
    rows.append("| Check | Status | Evidence |")
    rows.append("|---|---|---|")
    rows.append(check(result.get("result_model") == "V3_ATOMIC_BENCHMARK", "Canonical model", str(result.get("result_model")), failures))
    rows.append(check(len(records) == 52 and result.get("record_count") == 52, "Atomic cases", f"derived={len(records)} stored={result.get('record_count')}", failures))
    rows.append(check(derived_arms == Counter({"Core": 26, "Variant B": 26}), "Core/Variant B denominators", str(dict(derived_arms)), failures))
    rows.append(check(derived_pipelines == Counter({"LibreOffice": 26, "Google Docs": 26}), "Pipeline denominators", str(dict(derived_pipelines)), failures))
    rows.append(check(stored_counts == derived_counts, "Outcome counts", f"derived={dict(derived_counts)} stored={dict(stored_counts)}", failures))
    rows.append(check(sum(stored_counts.values()) == 52, "Outcome accounting", str(sum(stored_counts.values())), failures))
    rows.append(check(len(feature_ids) == 13, "Core feature families", f"{len(feature_ids)} feature fixtures", failures))
    rows.append(check(len(contract_files) == 13, "Contract files", f"{len(contract_files)} contracts", failures))
    rows.append(check(core_manifest.get("fixture_count") == 13 and len(core_manifest.get("fixtures", [])) == 13, "Core source manifest", f"declared={core_manifest.get('fixture_count')} entries={len(core_manifest.get('fixtures', []))}", failures))
    rows.append(check(variant.get("records") and len(variant["records"]) == 26, "Variant B result rows", str(len(variant.get("records", []))), failures))
    rows.append(check(historical.get("record_count") == 26 and len(historical.get("records", [])) == 26, "Historical Core record", str(historical.get("record_count")), failures))

    cal_counts = calibration.get("counts", {})
    rows.append(check(calibration.get("control_count") == len(calibration.get("rows", [])) == 27, "Calibration controls", str(calibration.get("control_count")), failures))
    rows.append(check(sum(cal_counts.values()) == 27, "Calibration accounting", str(cal_counts), failures))
    rows.append(check(repeatability.get("fixture_count") == 13 and repeatability.get("run_count") == 39, "Repeatability scope", f"fixtures={repeatability.get('fixture_count')} runs={repeatability.get('run_count')}", failures))
    rows.append(check(repeatability.get("byte_identical") == 13 and repeatability.get("classification_stable") == 13 and len(repeatability.get("records", [])) == 13, "Repeatability outcomes", f"byte_identical={repeatability.get('byte_identical')} stable={repeatability.get('classification_stable')}", failures))
    rows.append(check(integrated.get("documents") == 3 and len(integrated.get("records", [])) == 42 and integrated.get("primary_denominator_excluded") is True, "Integrated sanity arm", f"documents={integrated.get('documents')} observations={len(integrated.get('records', []))}", failures))
    manuscript_claims = {
        "52 atomic cases": r"All 52 atomic",
        "18 preserved": r"18 \verifiedpreserved{}",
        "4 partial": r"4 \observedpartial{}",
        "7 altered": r"7 \altered{}",
        "4 lost": r"4 \confirmedlost{}",
        "18 unresolved": r"18 \unresolved{}",
        "1 measurement error": r"1 \measured{}",
        "39 repeatability runs": r"39 total Google runs",
        "42 integrated observations": r"42 property--pipeline observations",
    }
    for label, phrase in manuscript_claims.items():
        rows.append(check(phrase in manuscript_text, f"Manuscript claim: {label}", phrase, failures))

    rows.append("")
    rows.append("## Canonical outcome counts")
    rows.append("")
    rows.append("| Outcome | Count |")
    rows.append("|---|---:|")
    for outcome in sorted(derived_counts):
        rows.append(f"| `{outcome}` | {derived_counts[outcome]} |")
    rows.append("")
    rows.append("## Canonical interpretation")
    rows.append("")
    rows.append("The 52-row V3 atomic record is the current primary denominator. The 26-row evidence-aware Core record, 26-row Variant B record, calibration, repeatability, and integrated records remain separately identifiable. Historical V1/V2 classifications are not silently rewritten.")
    return failures, rows


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write-report", action="store_true")
    args = parser.parse_args()
    failures, rows = audit()
    if args.write_report:
        report = ROOT / "reports" / "FINAL_CONSISTENCY_AUDIT.md"
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))
    if failures:
        print("\nFAILURES:")
        print("\n".join(f"- {failure}" for failure in failures))
        return 1
    print("\nALL CONSISTENCY CHECKS PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
